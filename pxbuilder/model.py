"""Data model for a generated PX sample script.

The GUI edits an instance of :class:`Script`; :mod:`pxbuilder.codegen` turns it
into Python source. Nothing in this module imports aqpxlib -- the builder is a
pure code generator and must work on machines with no PX software installed.

A script has three parts, mirroring how a test is written:

* :class:`Session` and :class:`Bus` plus a list of :class:`Device` -- the setup.
* A list of :class:`Step` -- what each device does. A controller send is a
  :class:`Step` holding an ordered list of :class:`Transaction`, which becomes an
  ``I3CControllerTransactionV2`` frame; everything else is a direct method call.
* Flows (see :mod:`pxbuilder.flows`) are just pre-built devices and steps.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

SCHEMA_VERSION = 2

#: The step `op` that means "send an I3CControllerTransactionV2 frame".
SEND_FRAME = "send_frame"


@dataclass
class Session:
    """Connection settings for AqProtocolExerciser.connect()."""

    port: int = 60600
    clear_handles: bool = True


@dataclass
class Bus:
    """Electrical + pin configuration of the I3C bus."""

    scl: int = 0
    sda: int = 1
    voltage: int = 3300
    la_threshold_voltage: int = 1600
    pullup_resistance: int = 500
    pulldown_resistance: int = 0


@dataclass
class Device:
    """A controller or target attached to the bus.

    ``kind`` is a key into :data:`pxbuilder.catalog.DEVICES`; ``params`` holds
    the values for that entry's parameter list, keyed by parameter name.
    """

    kind: str
    var: str
    params: dict[str, Any] = field(default_factory=dict)


@dataclass
class Transaction:
    """One entry of an ``I3CControllerTransactionV2`` frame.

    ``kind`` is a key into :data:`pxbuilder.catalog.TRANSACTIONS` -- one of the
    protobuf payloads the message carries (sdr_write, sdr_read, hdr_ddr_write,
    hdr_ddr_read, stop, idle_time).
    """

    kind: str
    params: dict[str, Any] = field(default_factory=dict)
    enabled: bool = True
    comment: str = ""


@dataclass
class Step:
    """One operation in the script body.

    For a controller send, ``op`` is :data:`SEND_FRAME` and ``transactions``
    holds the frame. Otherwise ``op`` is a key into
    :data:`pxbuilder.catalog.OPERATIONS` and the call is a plain method call on
    ``target_var``.
    """

    op: str
    target_var: str = ""
    params: dict[str, Any] = field(default_factory=dict)
    transactions: list[Transaction] = field(default_factory=list)
    enabled: bool = True
    comment: str = ""

    @property
    def is_frame(self) -> bool:
        """Whether this step emits a transaction frame rather than a call."""
        return self.op == SEND_FRAME


@dataclass
class Script:
    """The whole generated script."""

    name: str = "i3c_sample"
    description: str = "Generated by PX Py Builder"
    session: Session = field(default_factory=Session)
    bus: Bus = field(default_factory=Bus)
    devices: list[Device] = field(default_factory=list)
    steps: list[Step] = field(default_factory=list)
    log_results: bool = True
    #: Detach every device at the end. Off leaves the bus as the script left
    #: it, which is what you want when the next script expects it that way.
    detach_on_finish: bool = True

    # -- persistence -----------------------------------------------------

    def to_json(self) -> str:
        """Serialize to a project file."""
        payload = {"schema_version": SCHEMA_VERSION, **asdict(self)}
        return json.dumps(payload, indent=2, ensure_ascii=False)

    @classmethod
    def from_json(cls, text: str) -> "Script":
        """Load a project file written by :meth:`to_json`."""
        raw = json.loads(text)
        version = raw.pop("schema_version", SCHEMA_VERSION)
        if version > SCHEMA_VERSION:
            msg = f"Project uses schema version {version}, this build understands {SCHEMA_VERSION}"
            raise ValueError(msg)
        return cls(
            name=raw.get("name", "i3c_sample"),
            description=raw.get("description", ""),
            session=Session(**raw.get("session", {})),
            bus=Bus(**raw.get("bus", {})),
            devices=[Device(**d) for d in raw.get("devices", [])],
            steps=[cls._step_from(s) for s in raw.get("steps", [])],
            log_results=raw.get("log_results", True),
            detach_on_finish=raw.get("detach_on_finish", True),
        )

    @staticmethod
    def _step_from(raw: dict[str, Any]) -> Step:
        """Rebuild a step, tolerating v1 files that had no transactions."""
        return Step(
            op=raw["op"],
            target_var=raw.get("target_var", ""),
            params=raw.get("params", {}),
            transactions=[Transaction(**t) for t in raw.get("transactions", [])],
            enabled=raw.get("enabled", True),
            comment=raw.get("comment", ""),
        )

    def save(self, path: str | Path) -> None:
        """Write the project file to disk as UTF-8."""
        Path(path).write_text(self.to_json(), encoding="utf-8")

    @classmethod
    def load(cls, path: str | Path) -> "Script":
        """Read a project file from disk."""
        return cls.from_json(Path(path).read_text(encoding="utf-8"))

    # -- helpers ---------------------------------------------------------

    def device(self, var: str) -> Device | None:
        """Look up a device by its variable name."""
        return next((d for d in self.devices if d.var == var), None)

    def unique_var(self, base: str) -> str:
        """Return ``base``, suffixed with a number if it is already taken."""
        taken = {d.var for d in self.devices}
        if base not in taken:
            return base
        n = 2
        while f"{base}_{n}" in taken:
            n += 1
        return f"{base}_{n}"
